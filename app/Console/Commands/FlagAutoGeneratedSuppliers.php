<?php

namespace App\Console\Commands;

use App\Models\Catalog\Product;
use App\Models\Inventory\Supplier;
use App\Models\Inventory\SupplierProduct;
use App\Models\Organization\Organization;
use Illuminate\Console\Command;

class FlagAutoGeneratedSuppliers extends Command
{
    protected $signature = 'suppliers:flag-auto-generated
        {--org= : Organization id to process (required unless --all is set)}
        {--all : Process every organization}
        {--dry-run : Report what would change without writing}';

    protected $description = 'Backfill: flag pre-existing stub suppliers (auto-generated by import) and create missing consignor->product links.';

    public function handle(): int
    {
        $orgFilter = $this->option('org');
        $all = (bool) $this->option('all');
        $dryRun = (bool) $this->option('dry-run');

        if (! $orgFilter && ! $all) {
            $this->error('Must specify --org={id} or --all.');

            return self::FAILURE;
        }

        $orgIds = $all
            ? Organization::pluck('id')->all()
            : [$orgFilter];

        $stats = [
            'flagged' => 0,
            'already_flagged' => 0,
            'consignor_links_created' => 0,
            'consignor_links_existed' => 0,
            'products_with_consignor_attr' => 0,
            'consignor_supplier_missing' => 0,
        ];

        foreach ($orgIds as $orgId) {
            $this->line("Processing org {$orgId}...");

            // Step A: flag stubs by heuristic.
            $stubs = Supplier::where('organization_id', $orgId)
                ->whereNotNull('code')
                ->whereColumn('code', 'name')
                ->whereNull('email')
                ->whereNull('phone')
                ->whereNull('address_line1')
                ->get();

            foreach ($stubs as $s) {
                $meta = $s->meta_data ?? [];
                if (! empty($meta['auto_generated'])) {
                    $stats['already_flagged']++;

                    continue;
                }
                $meta['auto_generated'] = true;
                $stats['flagged']++;
                if (! $dryRun) {
                    $s->update(['meta_data' => $meta]);
                }
            }

            // Step B: backfill missing consignor->product SupplierProduct links.
            // Build a lookup of consignor code -> supplier id for this org.
            $consignorSuppliers = Supplier::where('organization_id', $orgId)
                ->where('meta_data->is_consignor', true)
                ->pluck('id', 'code');

            $products = Product::where('organization_id', $orgId)
                ->whereNotNull('attributes->consignor_code')
                ->get(['id', 'sku', 'attributes']);

            foreach ($products as $p) {
                $stats['products_with_consignor_attr']++;
                $consignorCode = $p->attributes['consignor_code'] ?? null;
                if (! $consignorCode) {
                    continue;
                }
                $supplierId = $consignorSuppliers[$consignorCode] ?? null;
                if (! $supplierId) {
                    $stats['consignor_supplier_missing']++;

                    continue;
                }

                $exists = SupplierProduct::where('supplier_id', $supplierId)
                    ->where('product_id', $p->id)
                    ->exists();

                if ($exists) {
                    $stats['consignor_links_existed']++;

                    continue;
                }

                $stats['consignor_links_created']++;
                if (! $dryRun) {
                    SupplierProduct::create([
                        'supplier_id' => $supplierId,
                        'product_id' => $p->id,
                        'supplier_sku' => $p->sku,
                        'cost_price' => 0,
                        'is_active' => true,
                    ]);
                }
            }
        }

        $this->info($dryRun ? 'Dry run complete.' : 'Backfill complete.');
        foreach ($stats as $k => $v) {
            $this->line(sprintf('  %-30s %d', $k, $v));
        }

        return self::SUCCESS;
    }
}
