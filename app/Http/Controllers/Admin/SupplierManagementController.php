    /**
     * Display supplier management dashboard
     */
    public function index(Request $request)
    {
        $user = Auth::user();
        abort_unless($user?->canViewSuppliers(), 403);
        $organizationId = $user->currentTeam?->organization_id ?? $user->current_organization_id ?? $user->organization_id;

        $query = Supplier::where('organization_id', $organizationId)
            ->with(['currentTier', 'commissionStructure']);

        // Apply status filter
        if ($request->filled('status')) {
            $status = $request->input('status');
            // Check if it's a supplier_status enum value
            $supplierStatusValues = array_column(SupplierStatus::cases(), 'value');
            if (in_array($status, $supplierStatusValues)) {
                $query->where('supplier_status', $status);
            } elseif ($status === 'active') {
                $query->where('is_active', true);
            } elseif ($status === 'inactive') {
                $query->where('is_active', false);
            }
        }

        // Apply tier filter
        if ($request->filled('tier')) {
            $query->where('current_tier_id', $request->input('tier'));
        }

        // Needs-review filter (auto-generated stubs)
        if ($request->input('filter') === 'needs-review') {
            $query->autoGenerated();
        }

        if ($request->filled('search')) {
            $search = $request->input('search');
            $query->where(function ($q) use ($search) {
                $q->where('name', 'ilike', "%{$search}%")
                    ->orWhere('email', 'ilike', "%{$search}%")
                    ->orWhere('code', 'ilike', "%{$search}%")
                    ->orWhere('company_name', 'ilike', "%{$search}%");
            });
        }

        // Sorting
        $sortField = $request->input('sort', 'created_at');
        $sortDirection = $request->input('direction', 'desc');
        $query->orderBy($sortField, $sortDirection);

        $suppliers = $query->paginate($request->input('per_page', 25));

        // Get summary stats
        $stats = $this->getSupplierStats($organizationId);

        // Get tiers for filter dropdown (wrapped in try/catch in case table doesn't exist)
        $tiers = [];
        try {
            $tiers = SupplierTier::where('organization_id', $organizationId)
                ->active()
                ->ordered()
                ->get(['id', 'tier_name as name', 'tier_code as code']);
        } catch (\Exception $e) {
            // Tiers table may not exist yet
        }

        $needsReviewCount = Supplier::where('organization_id', $organizationId)
            ->autoGenerated()
            ->count();

        return Inertia::render('Admin/Suppliers/Index', [
            'suppliers' => SupplierListResource::collection($suppliers),
            'stats' => $stats,
            'tiers' => $tiers,
            'commissionStructures' => $this->getCommissionStructures($organizationId),
            'filters' => $request->only(['status', 'tier', 'search', 'sort', 'direction', 'filter']),
            'needsReviewCount' => $needsReviewCount,
            'canManageAdminConfig' => $user->canManageSupplierAdminConfig(),
        ]);
    }

    /**
     * Update a supplier's settings from the edit modal
     */
    public function update(Request $request, $supplierId)
    {
        abort_unless(Auth::user()?->canViewSuppliers(), 403);
        $supplier = $this->getSupplier($supplierId);
        $canManageAdminConfig = Auth::user()?->canManageSupplierAdminConfig() ?? false;

        $request->validate([
            'status' => 'nullable|string|in:'.implode(',', array_column(SupplierStatus::cases(), 'value')),
            'tier_id' => 'nullable|uuid|exists:supplier_tiers,id',
            'commission_structure_id' => 'nullable|uuid|exists:commission_structures,id',
            'settlement_frequency' => 'nullable|string|in:per_sale,daily,weekly,bi_weekly,monthly,quarterly,custom',
            'notes' => 'nullable|string',
            // Profile fields (basic identification + contact + business terms)
            'name' => 'nullable|string|max:255',
            'company_name' => 'nullable|string|max:255',
            'email' => 'nullable|email|max:255',
            'phone' => 'nullable|string|max:50',
            'contact_name' => 'nullable|string|max:255',
            'address_line1' => 'nullable|string|max:255',
            'city' => 'nullable|string|max:100',
            'state' => 'nullable|string|max:100',
            'postal_code' => 'nullable|string|max:20',
            'country' => 'nullable|string|max:100',
            'business_type' => 'nullable|string|max:50',
            'payment_terms' => 'nullable|integer|min:0|max:365',
            'currency' => 'nullable|string|max:10',
            'is_consignor' => 'sometimes|boolean',
        ]);

        // Admin-config fields (status / tier / commission / settlement / notes)
        // — only owners and super admins can mutate. Manager/Admin requests
        // silently skip these even if the payload includes them, since the
        // front-end hides the section but a crafted request would otherwise
        // bypass it.
        if ($canManageAdminConfig) {
            // Update status
            if ($request->filled('status') && $request->input('status') !== $supplier->supplier_status?->value) {
                $supplier->update([
                    'supplier_status' => SupplierStatus::from($request->input('status')),
                    'status_changed_at' => now(),
                    'status_changed_by' => Auth::id(),
                ]);
            }

            // Update tier
            if ($request->filled('tier_id') && $request->input('tier_id') !== $supplier->current_tier_id) {
                try {
                    $newTier = SupplierTier::findOrFail($request->input('tier_id'));
                    $this->tierManager->manualTierChange($supplier, $newTier, Auth::user(), 'Updated via admin edit modal');
                } catch (\Throwable $e) {
                    // Fall back to direct update if tier manager fails
                    $supplier->update(['current_tier_id' => $request->input('tier_id')]);
                }
            }

            // Update commission structure
            if ($request->has('commission_structure_id')) {
                $supplier->update(['commission_structure_id' => $request->input('commission_structure_id') ?: null]);
            }

            // Update settlement schedule
            if ($request->filled('settlement_frequency') && $request->input('settlement_frequency') !== $supplier->settlement_schedule) {
                $supplier->update([
                    'settlement_schedule' => $request->input('settlement_frequency'),
                    'next_settlement_date' => $this->calculateNextSettlementDate($request->input('settlement_frequency')),
                ]);
            }

            // Update notes
            if ($request->has('notes')) {
                $supplier->update(['notes' => $request->input('notes')]);
            }
        }

        // Profile fields: identification, contact, business terms.
        // When the form sends any of these, save them in one update so
        // we can also clear the meta_data.auto_generated stub flag.
        $profileFields = [
            'name', 'company_name', 'email', 'phone', 'contact_name',
            'address_line1', 'city', 'state', 'postal_code', 'country',
            'business_type', 'payment_terms', 'currency',
        ];
        $profilePayload = $request->only($profileFields);
        $profilePayload = array_filter(
            $profilePayload,
            fn ($v) => $v !== null,
        );
        $hasConsignorToggle = $request->has('is_consignor');

        if (! empty($profilePayload) || $hasConsignorToggle) {
            $meta = $supplier->meta_data ?? [];
            if ($hasConsignorToggle) {
                $meta['is_consignor'] = $request->boolean('is_consignor');
            }
            // Saving profile clears the auto-generated stub flag.
            unset($meta['auto_generated']);
            $profilePayload['meta_data'] = $meta;
            $supplier->update($profilePayload);
        }

        return redirect()->route('admin.suppliers.index')->with('success', 'Supplier updated successfully.');
    }

    /**
     * Store a new supplier
     */
    public function store(Request $request)
    {
        $user = Auth::user();
        $organizationId = $user->currentTeam?->organization_id ?? $user->current_organization_id ?? $user->organization_id;

        $validator = Validator::make($request->all(), [
            'name' => 'required|string|max:255',
            'email' => 'nullable|email|max:255',
            'phone' => 'nullable|string|max:50',
            'contact_name' => 'nullable|string|max:255',
            'address' => 'nullable|string|max:500',
            'city' => 'nullable|string|max:100',
            'state' => 'nullable|string|max:100',
            'zip_code' => 'nullable|string|max:20',
            'country' => 'nullable|string|max:100',
            'notes' => 'nullable|string',
        ]);

        if ($validator->fails()) {
            return back()->withErrors($validator)->withInput();
        }

        $data = $validator->validated();
        $data['organization_id'] = $organizationId;

        Supplier::create($data);

        return redirect()->route('admin.suppliers.index')
            ->with('success', 'Supplier created successfully.');
    }

