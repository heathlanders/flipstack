    /**
     * Count active marketplace listings for the supplier's linked products
     * across eBay / Shopify / Amazon. Each marketplace stores listings in a
     * separate table and has no direct supplier FK, so we hop through products.
     */
    protected function countActiveMarketplaceListings($productIds): array
    {
        if ($productIds->isEmpty()) {
            return ['total' => 0, 'breakdown' => ['ebay' => 0, 'shopify' => 0, 'amazon' => 0]];
        }

        $breakdown = [
            'ebay' => EbayListing::whereIn('product_id', $productIds)
                ->where('status', EbayListing::STATUS_PUBLISHED)
                ->count(),
            'shopify' => ShopifyListing::whereIn('product_id', $productIds)
                ->where('status', ShopifyListing::STATUS_ACTIVE)
                ->count(),
            'amazon' => AmazonListing::whereIn('product_id', $productIds)
                ->where('status', AmazonListing::STATUS_ACTIVE)
                ->count(),
        ];

        return ['total' => array_sum($breakdown), 'breakdown' => $breakdown];
    }

    protected function openPurchaseOrderValue(Supplier $supplier): float
    {
        return (float) $supplier->purchaseOrders()
            ->whereIn('status', ['draft', 'submitted', 'partially_received'])
            ->sum('total_amount');
    }

    /**
     * Per-supplier procurement KPIs (lead time, on-time, receiving accuracy,
     * total spend) computed directly so we don't share the org-wide cache used
     * by ProcurementAnalyticsService.
     */
    protected function buildSupplierProcurementKpis(Supplier $supplier): array
    {
        $row = DB::table('purchase_orders')
            ->where('supplier_id', $supplier->id)
            ->whereNull('deleted_at')
            ->selectRaw('
                COUNT(*) as po_count,
                COALESCE(SUM(total_amount), 0) as total_spend,
                COALESCE(AVG(EXTRACT(EPOCH FROM (received_at - order_date::timestamp)) / 86400)
                    FILTER (WHERE received_at IS NOT NULL AND order_date IS NOT NULL), 0) as avg_lead_time_days,
                COUNT(*) FILTER (WHERE received_at IS NOT NULL AND expected_delivery_date IS NOT NULL
                    AND received_at::date <= expected_delivery_date) as on_time_count,
                COUNT(*) FILTER (WHERE received_at IS NOT NULL AND expected_delivery_date IS NOT NULL) as with_expected
            ')
            ->first();

        $accuracy = DB::table('purchase_order_items')
            ->join('purchase_orders', 'purchase_order_items.purchase_order_id', '=', 'purchase_orders.id')
            ->where('purchase_orders.supplier_id', $supplier->id)
            ->whereNull('purchase_orders.deleted_at')
            ->where('purchase_order_items.quantity_ordered', '>', 0)
            ->selectRaw('
                COUNT(*) as total_items,
                COUNT(*) FILTER (WHERE purchase_order_items.quantity_received = purchase_order_items.quantity_ordered) as exact_match,
                COUNT(*) FILTER (WHERE purchase_order_items.quantity_received < purchase_order_items.quantity_ordered) as under_received,
                COUNT(*) FILTER (WHERE purchase_order_items.quantity_received > purchase_order_items.quantity_ordered) as over_received
            ')
            ->first();

        $withExpected = (int) $row->with_expected;
        $totalItems = (int) $accuracy->total_items;

        return [
            'po_count' => (int) $row->po_count,
            'total_spend' => round((float) $row->total_spend, 2),
            'avg_lead_time_days' => round((float) $row->avg_lead_time_days, 2),
            'on_time_rate' => $withExpected > 0
                ? round(((int) $row->on_time_count / $withExpected) * 100, 2)
                : null,
            'receiving_accuracy' => $totalItems > 0
                ? round(((int) $accuracy->exact_match / $totalItems) * 100, 2)
                : null,
            'items_under_received' => (int) $accuracy->under_received,
            'items_over_received' => (int) $accuracy->over_received,
            'total_payouts' => round((float) $supplier->total_commissions_paid ?? 0, 2),
        ];
    }

    /**
     * Cross-reference lister_initials (eBay SKU parser) against actual supplier
     * links. Helps admin spot products that share a lister code with this
     * supplier but were never linked via the supplier_products pivot.
     */
    protected function buildListerCrossReference(Supplier $supplier): array
    {
        $orgId = $supplier->organization_id;

        $ebayCred = IntegrationCredential::where('organization_id', $orgId)
            ->where('platform', 'ebay')
            ->first();
        $knownListers = array_values((array) ($ebayCred?->config['known_listers'] ?? []));

        // Pluck distinct lister codes appearing on this supplier's linked products.
        $supplierListerCodes = DB::table('supplier_products')
            ->join('products', 'supplier_products.product_id', '=', 'products.id')
            ->where('supplier_products.supplier_id', $supplier->id)
            ->whereNotNull(DB::raw("products.attributes->>'lister_initials'"))
            ->selectRaw("DISTINCT products.attributes->>'lister_initials' as code")
            ->pluck('code')
            ->filter()
            ->values()
            ->all();

        // Org-wide products tagged with a lister code but missing a supplier link.
        $unlinkedCount = DB::table('products')
            ->leftJoin('supplier_products', 'supplier_products.product_id', '=', 'products.id')
            ->where('products.organization_id', $orgId)
            ->whereNotNull(DB::raw("products.attributes->>'lister_initials'"))
            ->whereNull('supplier_products.id')
            ->count();

        return [
            'known_lister_codes' => $knownListers,
            'supplier_lister_codes' => $supplierListerCodes,
            'org_unlinked_lister_products' => $unlinkedCount,
        ];
    }

    /**
     * Assemble a Recent Activity feed from settlements, tier changes,
     * status changes, and recent POs.
     */
    protected function buildRecentActivity(Supplier $supplier, $settlements, $tierHistory): array
    {
        $events = collect();

        foreach ($settlements->take(5) as $s) {
            $events->push([
                'id' => 'settlement-'.$s->id,
                'type' => 'settlement',
                'description' => 'Settlement '.($s->settlement_number ?? substr((string) $s->id, 0, 8))
                    .' for $'.number_format((float) ($s->net_amount ?? 0), 2),
                'created_at' => $s->created_at,
            ]);
        }

        foreach (collect($tierHistory)->take(5) as $t) {
            $events->push([
                'id' => 'tier-'.($t->id ?? $t['id'] ?? uniqid()),
                'type' => 'tier_change',
                'description' => 'Tier change recorded',
                'created_at' => $t->created_at ?? $t['created_at'] ?? now(),
            ]);
        }

        if ($supplier->status_changed_at) {
            $events->push([
                'id' => 'status-'.$supplier->id,
                'type' => 'status_change',
                'description' => 'Status changed to '.($supplier->supplier_status?->label() ?? 'unknown'),
                'created_at' => $supplier->status_changed_at,
            ]);
        }

        $recentPos = $supplier->purchaseOrders()
            ->latest('created_at')
            ->take(5)
            ->get(['id', 'po_number', 'status', 'total_amount', 'created_at']);

        foreach ($recentPos as $po) {
            $events->push([
                'id' => 'po-'.$po->id,
                'type' => 'sale',
                'description' => 'PO '.$po->po_number.' ('.$po->status.') $'
                    .number_format((float) $po->total_amount, 2),
                'created_at' => $po->created_at,
            ]);
        }

        return $events
            ->sortByDesc(fn ($e) => $e['created_at'] instanceof \DateTimeInterface
                ? $e['created_at']->getTimestamp()
                : strtotime((string) $e['created_at']))
            ->take(10)
            ->values()
            ->all();
    }

