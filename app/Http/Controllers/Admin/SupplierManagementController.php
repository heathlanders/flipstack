    /**
     * Bulk update suppliers
     */
    public function bulkUpdate(Request $request)
    {
        abort_unless(Auth::user()?->canManageSupplierAdminConfig(), 403);

        $request->validate([
            'supplier_ids' => 'required|array|min:1',
            'supplier_ids.*' => 'uuid|exists:suppliers,id',
            'action' => 'required|string|in:update_status,update_tier,update_commission,send_notification',
            'data' => 'required|array',
        ]);

        $supplierIds = $request->input('supplier_ids');
        $action = $request->input('action');
        $data = $request->input('data');

        $results = ['success' => 0, 'failed' => 0, 'errors' => []];

        foreach ($supplierIds as $supplierId) {
            try {
                $supplier = $this->getSupplier($supplierId);

                switch ($action) {
                    case 'update_status':
                        $supplier->update([
                            'supplier_status' => $data['status'],
                            'status_changed_at' => now(),
                            'status_changed_by' => Auth::id(),
                        ]);
                        break;

                    case 'update_tier':
                        $this->tierManager->manualTierChange(
                            $supplier,
                            SupplierTier::find($data['tier_id']),
                            Auth::user(),
                            $data['reason'] ?? 'Bulk tier update'
                        );
                        break;

                    case 'update_commission':
                        $supplier->update([
                            'commission_structure_id' => $data['commission_structure_id'],
                        ]);
                        break;

                    case 'send_notification':
                        SupplierNotification::createForSupplier(
                            $supplier,
                            $data['title'],
                            $data['message'],
                            $data['type'] ?? 'info',
                            $data['category'] ?? 'system'
                        );
                        break;
                }

                $results['success']++;
            } catch (\Exception $e) {
                $results['failed']++;
                $results['errors'][] = [
                    'supplier_id' => $supplierId,
                    'error' => $e->getMessage(),
                ];
            }
        }

        return response()->json([
            'message' => "Bulk update completed: {$results['success']} succeeded, {$results['failed']} failed",
            'results' => $results,
        ]);
    }

