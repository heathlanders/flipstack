    /**
     * Get supplier statistics
     */
    protected function getSupplierStats($organizationId): array
    {
        $stats = Supplier::where('organization_id', $organizationId)
            ->selectRaw("
                COUNT(*) as total,
                COUNT(CASE WHEN is_active = true THEN 1 END) as active,
                COUNT(CASE WHEN is_active = false THEN 1 END) as inactive,
                COUNT(CASE WHEN is_preferred = true THEN 1 END) as preferred,
                COUNT(CASE WHEN supplier_status = 'pending' THEN 1 END) as pending,
                COUNT(CASE WHEN supplier_status = 'onboarding' THEN 1 END) as onboarding,
                COUNT(CASE WHEN supplier_status = 'suspended' THEN 1 END) as suspended,
                COUNT(CASE WHEN supplier_status = 'terminated' THEN 1 END) as terminated
            ")
            ->first();

        // Pending settlements amount - wrapped in try/catch in case table doesn't exist
        $pendingSettlements = 0;
        try {
            $pendingSettlements = Settlement::where('organization_id', $organizationId)
                ->pending()
                ->sum('net_amount');
        } catch (\Exception $e) {
            // Settlements table may not exist yet
        }

        return [
            'total' => $stats->total ?? 0,
            'active' => $stats->active ?? 0,
            'inactive' => $stats->inactive ?? 0,
            'preferred' => $stats->preferred ?? 0,
            'pending' => $stats->pending ?? 0,
            'onboarding' => $stats->onboarding ?? 0,
            'suspended' => $stats->suspended ?? 0,
            'terminated' => $stats->terminated ?? 0,
            'pending_settlements' => round($pendingSettlements, 2),
        ];
    }

