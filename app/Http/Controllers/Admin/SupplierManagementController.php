    /**
     * Export suppliers list
     */
    public function export(Request $request)
    {
        $user = Auth::user();
        $organizationId = $user->currentTeam?->organization_id ?? $user->current_organization_id ?? $user->organization_id;

        $suppliers = Supplier::where('organization_id', $organizationId)
            ->with(['currentTier', 'commissionStructure'])
            ->get();

        $csvData = [];
        $csvData[] = [
            'ID', 'Name', 'Email', 'Company', 'Status', 'Tier',
            'Commission Structure', 'Performance Score', 'Total Sales YTD',
            'Settlement Schedule', 'Created At',
        ];

        foreach ($suppliers as $supplier) {
            $csvData[] = [
                $supplier->id,
                $supplier->name,
                $supplier->email,
                $supplier->company_name,
                $supplier->supplier_status?->value,
                $supplier->currentTier?->tier_name,
                $supplier->commissionStructure?->name,
                $supplier->cached_performance_score,
                $supplier->total_sales_ytd,
                $supplier->settlement_schedule,
                $supplier->created_at->format('Y-m-d'),
            ];
        }

        $filename = 'suppliers-export-'.now()->format('Y-m-d').'.csv';
        $handle = fopen('php://temp', 'r+');

        foreach ($csvData as $row) {
            fputcsv($handle, $row);
        }

        rewind($handle);
        $csv = stream_get_contents($handle);
        fclose($handle);

        return response($csv)
            ->header('Content-Type', 'text/csv')
            ->header('Content-Disposition', "attachment; filename=\"{$filename}\"");
    }

    /**
     * Get supplier activity log
     */
    public function activityLog(Request $request, $supplierId)
    {
        $supplier = $this->getSupplier($supplierId);

        $activities = [];

        // Tier changes
        $tierChanges = SupplierTierHistory::forSupplier($supplierId)
            ->with(['fromTier', 'toTier', 'changedBy'])
            ->latest()
            ->take(20)
            ->get()
            ->map(fn ($h) => [
                'type' => 'tier_change',
                'date' => $h->created_at,
                'description' => "Tier changed from {$h->fromTier?->tier_name} to {$h->toTier?->tier_name}",
                'user' => $h->changedBy?->name,
                'details' => $h->reason,
            ]);

        // Settlements
        $settlements = Settlement::forSupplier($supplierId)
            ->latest()
            ->take(20)
            ->get()
            ->map(fn ($s) => [
                'type' => 'settlement',
                'date' => $s->created_at,
                'description' => "Settlement #{$s->settlement_number} - {$s->status->label()}",
                'details' => 'Amount: $'.number_format($s->net_amount, 2),
            ]);

        // Merge and sort
        $activities = collect([...$tierChanges, ...$settlements])
            ->sortByDesc('date')
            ->take(50)
            ->values();

        return response()->json([
            'activities' => $activities,
        ]);
    }

