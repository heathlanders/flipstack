    public function products(Request $request, $supplierId)
    {
        abort_unless(Auth::user()?->canViewSuppliers(), 403);
        $supplier = $this->getSupplier($supplierId);

        $search = trim((string) $request->input('search', ''));
        $sort = $request->input('sort', 'created_at');
        $direction = $request->input('direction', 'desc') === 'asc' ? 'asc' : 'desc';

        $sortable = [
            'sku' => 'products.sku',
            'name' => 'products.name',
            'price' => 'products.selling_price',
            'stock' => 'products.stock_quantity',
            'created_at' => 'products.created_at',
        ];
        $sortColumn = $sortable[$sort] ?? $sortable['created_at'];

        $query = $supplier->products()
            ->select([
                'products.id',
                'products.sku',
                'products.name',
                'products.selling_price',
                'products.stock_quantity',
                'products.status',
            ])
            ->withPivot(['cost_price', 'supplier_sku', 'is_preferred', 'is_active', 'quality_rating']);

        if ($search !== '') {
            $query->where(function ($q) use ($search) {
                $q->where('products.sku', 'ilike', "%{$search}%")
                    ->orWhere('products.name', 'ilike', "%{$search}%");
            });
        }

        $products = $query->orderBy($sortColumn, $direction)
            ->paginate(25)
            ->withQueryString();

        return response()->json($products);
    }

